            orientation=LinearLayout.VERTICAL
            setPadding(dip(20),dip(8),dip(20),dip(10))
        }
        content.addView(TextView(this).apply {
            text="Этап 1: на стоящей машине вынь телефон из магнитного крепления. " +
                "Вдали от металла вращай его восьмёркой во всех плоскостях "+
                "15 секунд. Нужны 25+ замеров, изменение поля по двум осям "+
                "и достоверный компас.\n\n"+
                "Этап 2: закрепи телефон в рабочем положении, нажми "+
                "«Привязка к GPS». При хорошем GPS едь прямо со скоростью "+
                "от 15 км/ч. Привязка завершится автоматически после "+
                "четырёх устойчивых измерений. Во время движения "+
                "телефоном пользоваться не нужно."
            textSize=15f
            setTextColor(primaryText)
        })
        val result=TextView(this).apply {
            text=State.compassAccuracyText+"\n"+State.compassCalibrationText
            textSize=14f
            setTextColor(Color.rgb(142,195,251))
            setPadding(0,dip(12),0,0)
        }
        compassDialogStatus=result
        content.addView(result)
        val dialog=AlertDialog.Builder(this)
            .setTitle("Проверка и калибровка компаса")
            .setView(content)
            .setPositiveButton("Начать 15 с",null)
            .setNeutralButton("Привязка к GPS",null)
            .setNegativeButton("Закрыть",null)
            .create()
        dialog.setOnShowListener {
            dialog.getButton(AlertDialog.BUTTON_POSITIVE).setOnClickListener {
                send(NavService.CHECK_COMPASS)
                result.text="Запрос на проверку. "+State.compassCalibrationText
            }
            dialog.getButton(AlertDialog.BUTTON_NEUTRAL).setOnClickListener {
                send(NavService.ALIGN_COMPASS)
                result.text="GPS-привязка: "+State.compassAlignmentText
            }
        }
        dialog.setOnDismissListener { compassDialogStatus=null }
        dialog.show()
    }

    private fun showAlertOblastPicker() {
        val options=AirAlerts.oblasts
        val selected=options.indexOfFirst {
            it.slug==AirAlerts.currentOblast().slug
        }.coerceAtLeast(0)
        AlertDialog.Builder(this)
            .setTitle("Область для тревог")
            .setSingleChoiceItems(options.map{it.name}.toTypedArray(),selected){dialog,index->
                AirAlerts.selectOblast(this,options[index].slug)
                showAlertStatus()
                dialog.dismiss()
            }
            .setNegativeButton("Отмена",null).show()
    }

    private fun showAlertCityPicker() {
        // "Нет": the selected oblast becomes the automatic DR alert gate.
        // Tryvoha.online has a separate city-level record for Kyiv only.
        val options=AirAlerts.cities
        val selected=options.indexOfFirst {
            it.slug==AirAlerts.currentCity().slug
        }.coerceAtLeast(0)
        AlertDialog.Builder(this)
            .setTitle("Город: Киев или Нет (по области)")
            .setSingleChoiceItems(options.map{it.name}.toTypedArray(),selected){dialog,index->
                AirAlerts.selectCity(this,options[index].slug)
                showAlertStatus()
                dialog.dismiss()
            }
            .setNeutralButton("Об источнике"){_,_->
                AlertDialog.Builder(this)
                    .setTitle("Тревоги городов")
                    .setMessage("Tryvoha.online предоставляет отдельный статус " +
                        "города Киева. Для остальных городов в этом источнике " +
                        "есть статусы областей и районов, которые нельзя " +
                        "приравнивать к тревоге именно в городе.")
                    .setPositiveButton("Понятно",null).show()
            }
            .setNegativeButton("Отмена",null).show()
    }

    private fun showSettingsMenu() {
        val list=LinearLayout(this).apply {
            orientation=LinearLayout.VERTICAL
            setPadding(dip(14),dip(3),dip(14),dip(8))
        }
        val scroll=ScrollView(this).apply {
            addView(list)
            isFillViewport=false
        }
        val dialog=AlertDialog.Builder(this).setTitle("Настройки")
            .setView(scroll).setNegativeButton("Закрыть",null).create()
        fun section(name: String) {
            list.addView(TextView(this).apply {
                text=name
                textSize=13f
                typeface=android.graphics.Typeface.DEFAULT_BOLD
                setTextColor(Color.rgb(142,195,251))
                setPadding(0,dip(18),0,dip(7))
            })
            list.addView(View(this).apply { setBackgroundColor(Color.rgb(85,95,110)) },
                LinearLayout.LayoutParams(LinearLayout.LayoutParams.MATCH_PARENT,dip(1)))
        }
        fun item(caption: String, action: ()->Unit) {
            list.addView(TextView(this).apply {
                text=caption
                textSize=15f
                setTextColor(primaryText)
                setPadding(dip(8),dip(14),dip(8),dip(14))
                setOnClickListener { dialog.dismiss();action() }
            },LinearLayout.LayoutParams(LinearLayout.LayoutParams.MATCH_PARENT,
                LinearLayout.LayoutParams.WRAP_CONTENT))
