            showAlertOblastPicker()
        }
        item("Город · "+AirAlerts.currentCity().name) {
            showAlertCityPicker()
        }

        dialog.show()
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val scroll = ScrollView(this).apply {
            setBackgroundColor(bgColor)
            clipToPadding = false
            // Android 15/16 enforces edge-to-edge drawing: reserve the
            // status bar, display cutout and gesture navigation space.
            setOnApplyWindowInsetsListener { view, windowInsets ->
                val bars = windowInsets.getInsets(
                    WindowInsets.Type.systemBars() or WindowInsets.Type.displayCutout()
                )
                view.setPadding(bars.left, bars.top, bars.right, bars.bottom)
                windowInsets
            }
        }
        window.statusBarColor=bgColor
        window.navigationBarColor=bgColor
        window.decorView.systemUiVisibility=0
        window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
        root = LinearLayout(this).apply {
            orientation=LinearLayout.VERTICAL
            setPadding(dip(16),dip(14),dip(16),dip(24))
            setBackgroundColor(bgColor)
        }
        State.obdFactor=NavigatorPrefs(this).obdFactor
        scroll.addView(root); setContentView(scroll)
        addAlertHeader()
        addSpeedPanels()
        status = TextView(this).apply {
            textSize = 15f
            setTextColor(secondaryText)
            setPadding(dip(4), dip(8), dip(4), dip(15))
        }
        root.addView(status)
        addSensorCards()
        addButton(root,"Вернуться к Google Maps") { finish() }
        addButton(root,"Настройки") { showSettingsMenu() }
        addButton(root,"Остановить мониторинг") { send(NavService.EXIT) }
        handler.post {showStartupPermissionsIfMissing()}
        // Offline maps are checked on the offline screen, and are never
        // downloaded from a user-configured oblast HTTPS server at startup.
        // Existing Ukraine map/address files survive APK updates.
    }
    override fun onResume() {
        super.onResume()
        monitorGpsSpeed()
        if(hasPermissions()) send(NavService.MONITOR)
        handler.removeCallbacks(refresh)
        handler.post(refresh)
    }

    override fun onPause() {
        handler.removeCallbacks(refresh)
        picker?.dismiss()
        try { locationManager.removeUpdates(gpsSpeedListener) } catch (_: Exception) {}
        super.onPause()
    }

    override fun onRequestPermissionsResult(
        requestCode: Int, permissions: Array<out String>, grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if(requestCode==12) {
            monitorGpsSpeed()
            if(hasPermissions()) {
                send(NavService.MONITOR)
            } else {
                AlertDialog.Builder(this)
                    .setTitle("Не все разрешения выданы")
                    .setMessage("Для OBD и инерциальной навигации нужны "+
                        "точное местоположение и разрешения Bluetooth. "+
                        "При запрете через Android их можно включить в настройках.")
                    .setPositiveButton("Открыть настройки"){_,_->
                        openApplicationPermissions()
                    }
                    .setNegativeButton("Позже",null).show()
            }
        }
    }
