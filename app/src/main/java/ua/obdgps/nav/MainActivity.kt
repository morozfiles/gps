    private fun send(action: String, address: String? = null) {
        if (!hasPermissions()) { checkBluetoothGps(); return }
        val i = Intent(this, NavService::class.java).setAction(action)
        if (address != null) i.putExtra("address",address)
        try { startForegroundService(i) } catch (e: Exception) { State.message = e.message ?: "Ошибка запуска" }
    }
    private fun hasPermissions() = arrayOf(
        Manifest.permission.ACCESS_FINE_LOCATION,
        Manifest.permission.BLUETOOTH_SCAN,
        Manifest.permission.BLUETOOTH_CONNECT
    ).all { checkSelfPermission(it) == PackageManager.PERMISSION_GRANTED }
    private fun askPermissions() {
        requestPermissions(arrayOf(Manifest.permission.ACCESS_FINE_LOCATION,
          Manifest.permission.ACCESS_COARSE_LOCATION,Manifest.permission.BLUETOOTH_SCAN,
          Manifest.permission.BLUETOOTH_CONNECT,Manifest.permission.POST_NOTIFICATIONS),12)
    }
    private fun chooseBluetooth() {
        if (!hasPermissions() || !isBluetoothEnabled()) {
            checkBluetoothGps()
        } else {
            State.devices.clear()
            send(NavService.SCAN)
            showDevicePicker()
        }
    }

    private fun showProtocolChoice() {
        val items=arrayOf(
            "OBD2 K-Line (Space Star 2003)",
            "OBD2 CAN (11/29 бит, 250/500 кбит/с)",
            "OBD2 авто (CAN + K-Line)",
            "Mitsubishi MUT-II (эксперимент)"
        )
        val mode=NavigatorPrefs(this).protocolMode
        val selected=when(mode) {
            "CAN"->1
            "AUTO"->2
            "MUT"->3
            else->0
        }
        val actions=arrayOf(
            NavService.SET_OBD,NavService.SET_CAN,
            NavService.SET_AUTO,NavService.SET_MUT
        )
        AlertDialog.Builder(this).setTitle("Протокол двигателя")
            .setSingleChoiceItems(items,selected){dlg,index->
                send(actions[index])
                dlg.dismiss()
            }
            .setNegativeButton("Отмена",null).show()
    }

