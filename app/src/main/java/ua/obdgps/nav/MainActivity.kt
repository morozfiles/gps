    private val gpsSpeedListener = object : LocationListener {
        override fun onLocationChanged(location: Location) {
            // Mock GPS values generated by this app are NOT an independent GPS speed.
            if (location.isMock || State.dr) return
            if (location.provider != LocationManager.GPS_PROVIDER) return
            if (!location.hasSpeed() || !location.hasAccuracy() || location.accuracy > 75f) return
            val kmh = location.speed.toDouble() * 3.6
            if (!kmh.isFinite() || kmh !in 0.0..350.0) return
            gpsSpeedKmh = kmh
            gpsSpeedUpdatedElapsedMs = SystemClock.elapsedRealtime()
        }
    }

    private fun isGpsEnabled() = runCatching {
        locationManager.isProviderEnabled(LocationManager.GPS_PROVIDER)
    }.getOrDefault(false)

    private fun isBluetoothEnabled() = runCatching {
        bluetoothManager.adapter?.isEnabled == true
    }.getOrDefault(false)

    private fun monitorGpsSpeed() {
        // Remove first so coming back from GPS settings cannot duplicate listeners.
        try { locationManager.removeUpdates(gpsSpeedListener) } catch (_: Exception) {}
        if (checkSelfPermission(Manifest.permission.ACCESS_FINE_LOCATION)
            != PackageManager.PERMISSION_GRANTED || !isGpsEnabled()) return
        try {
            locationManager.requestLocationUpdates(
                LocationManager.GPS_PROVIDER, 1000L, 0f, gpsSpeedListener, Looper.getMainLooper()
            )
        } catch (e: Exception) {
            State.message = "GPS: ${e.localizedMessage ?: "ошибка датчика"}"
        }
    }

    private fun speedLabel(value: Double?, lastMs: Long): String {
        if (value == null || lastMs <= 0L
            || SystemClock.elapsedRealtime() - lastMs > 5000L) return "—"
        return String.format(Locale.getDefault(), "%.1f", value)
    }

