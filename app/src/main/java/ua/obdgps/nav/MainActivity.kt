                "\nРазрешения: " + (if (permissionOk) "предоставлены ✓" else "не предоставлены ✕")
            textSize = 17f
            setTextColor(secondaryText)
        })
        val dialog = AlertDialog.Builder(this)
            .setTitle("Проверка Bluetooth и GPS")
            .setView(content)
            .setNegativeButton("Закрыть", null)
            .create()
        fun action(caption: String, callback: () -> Unit) {
            content.addView(Button(this).apply {
                text = caption
                isAllCaps = false
                setOnClickListener { dialog.dismiss(); callback() }
            })
        }
        if (!permissionOk) action("Выдать разрешения") { askPermissions() }
        if (!bt) action("Включить Bluetooth") {
            try {
                startActivity(Intent(BluetoothAdapter.ACTION_REQUEST_ENABLE))
            } catch (e: Exception) {
                Toast.makeText(this, "Не удалось открыть Bluetooth: ${e.message}", Toast.LENGTH_LONG).show()
                try { startActivity(Intent(Settings.ACTION_BLUETOOTH_SETTINGS)) } catch (_: Exception) {}
            }
        }
        if (!gps) action("Открыть настройки GPS") {
            try {
                startActivity(Intent(Settings.ACTION_LOCATION_SOURCE_SETTINGS))
            } catch (e: Exception) {
                Toast.makeText(this, "Не удалось открыть GPS: ${e.message}", Toast.LENGTH_LONG).show()
            }
        }
        action("Проверить ещё раз") { checkBluetoothGps() }
        dialog.show()
    }
