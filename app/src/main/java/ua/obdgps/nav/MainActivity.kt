class MainActivity : Activity() {
    private val handler = Handler(Looper.getMainLooper())
    private lateinit var root: LinearLayout
    private lateinit var status: TextView
    private lateinit var sensorStatus: TextView
    private lateinit var gpsSpeedValue: TextView
    private lateinit var obdSpeedValue: TextView
    private var gpsSpeedKmh: Double? = null
    private var gpsSpeedUpdatedElapsedMs = 0L
    private val locationManager by lazy { getSystemService(LocationManager::class.java) }
    private val bluetoothManager by lazy { getSystemService(BluetoothManager::class.java) }
    private val gpsSpeedListener = object : LocationListener {
        override fun onLocationChanged(location: Location) {
            // Mock GPS values generated by this app are NOT an independent GPS speed.
            if (location.isMock || State.dr) return
            if (location.provider != LocationManager.GPS_PROVIDER) return
            if (!location.hasSpeed() || !location.hasAccuracy() || location.accuracy > 75f) return
            val kmh = location.speed.toDouble() * 3.6
            if (!kmh.isFinite() || kmh !in 0.0..350.0) return
            gpsSpeedKmh = kmh
            gpsSpeedUpdatedElapsedMs = SystemClock.elapsedRealtime()
        }
    }

    private fun isGpsEnabled() = runCatching {
        locationManager.isProviderEnabled(LocationManager.GPS_PROVIDER)
    }.getOrDefault(false)

    private fun isBluetoothEnabled() = runCatching {
        bluetoothManager.adapter?.isEnabled == true
    }.getOrDefault(false)

    private fun monitorGpsSpeed() {
        // Remove first so coming back from GPS settings cannot duplicate listeners.
        try { locationManager.removeUpdates(gpsSpeedListener) } catch (_: Exception) {}
        if (checkSelfPermission(Manifest.permission.ACCESS_FINE_LOCATION)
            != PackageManager.PERMISSION_GRANTED || !isGpsEnabled()) return
        try {
            locationManager.requestLocationUpdates(
                LocationManager.GPS_PROVIDER, 1000L, 0f, gpsSpeedListener, Looper.getMainLooper()
            )
        } catch (e: Exception) {
            State.message = "GPS: ${e.localizedMessage ?: "ошибка датчика"}"
        }
    }

    private fun speedLabel(value: Double?, lastMs: Long): String {
        if (value == null || lastMs <= 0L
            || SystemClock.elapsedRealtime() - lastMs > 5000L) return "—"
        return String.format(Locale.getDefault(), "%.1f", value)
    }

    private fun addSpeedPanels() {
        val line = LinearLayout(this).apply {
            orientation = LinearLayout.HORIZONTAL
            setPadding(0, dip(12), 0, dip(10))
        }
        fun addPanel(name: String): TextView {
            val panel = LinearLayout(this).apply {
                orientation = LinearLayout.VERTICAL
                gravity = Gravity.CENTER
                setPadding(dip(6), dip(12), dip(6), dip(12))
                background = GradientDrawable().apply {
                    cornerRadius = dip(12).toFloat()
                    setColor(Color.rgb(239, 243, 249))
                }
            }
            panel.addView(TextView(this).apply {
                text = name
                textSize = 15f
                setTextColor(Color.rgb(70, 83, 102))
            })
            val number = TextView(this).apply {
                text = "—"
                textSize = 31f
                setTextColor(Color.BLACK)
                gravity = Gravity.CENTER
                typeface = android.graphics.Typeface.DEFAULT_BOLD
            }
            panel.addView(number)
            panel.addView(TextView(this).apply {
                text = "км/ч"
                textSize = 12f
                setTextColor(Color.DKGRAY)
            })
            line.addView(panel, LinearLayout.LayoutParams(0,
                LinearLayout.LayoutParams.WRAP_CONTENT, 1f).apply {
                setMargins(dip(4), 0, dip(4), 0)
            })
            return number
        }
        gpsSpeedValue = addPanel("GPS")
        obdSpeedValue = addPanel("OBD")
        root.addView(line)
    }

    private fun checkBluetoothGps() {
        val permissionOk = hasPermissions()
        val bt = isBluetoothEnabled()
        val gps = isGpsEnabled()
        val content = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(dip(22), dip(10), dip(22), dip(6))
        }
        content.addView(TextView(this).apply {
            text = "Bluetooth: " + (if (bt) "включён ✓" else "выключен ✕") +
                "\nGPS: " + (if (gps) "включён ✓" else "выключен ✕") +
                "\nРазрешения: " + (if (permissionOk) "предоставлены ✓" else "не предоставлены ✕")
            textSize = 17f
            setTextColor(Color.DKGRAY)
        })
        val dialog = AlertDialog.Builder(this)
            .setTitle("Проверка Bluetooth и GPS")
            .setView(content)
            .setNegativeButton("Закрыть", null)
            .create()
        fun action(caption: String, callback: () -> Unit) {
            content.addView(Button(this).apply {
                text = caption
                isAllCaps = false
                setOnClickListener { dialog.dismiss(); callback() }
            })
        }
        if (!permissionOk) action("Выдать разрешения") { askPermissions() }
        if (!bt) action("Включить Bluetooth") {
            try {
                startActivity(Intent(BluetoothAdapter.ACTION_REQUEST_ENABLE))
            } catch (e: Exception) {
                Toast.makeText(this, "Не удалось открыть Bluetooth: ${e.message}", Toast.LENGTH_LONG).show()
                try { startActivity(Intent(Settings.ACTION_BLUETOOTH_SETTINGS)) } catch (_: Exception) {}
            }
        }
        if (!gps) action("Открыть настройки GPS") {
            try {
                startActivity(Intent(Settings.ACTION_LOCATION_SOURCE_SETTINGS))
            } catch (e: Exception) {
                Toast.makeText(this, "Не удалось открыть GPS: ${e.message}", Toast.LENGTH_LONG).show()
            }
        }
        action("Проверить ещё раз") { checkBluetoothGps() }
        dialog.show()
    }
    private lateinit var alertDot: View
    private lateinit var alertLabel: TextView
    private val kyivClock = DateTimeFormatter.ofPattern("HH:mm").withZone(ZoneId.of("Europe/Kyiv"))

    private fun dip(value: Int): Int = (value * resources.displayMetrics.density + 0.5f).toInt()

    private fun paintAlertDot(color: Int) {
        alertDot.background = GradientDrawable().apply {
            shape = GradientDrawable.OVAL
            setColor(color)
            setStroke(dip(1), Color.DKGRAY)
        }
    }

    private fun showAlertStatus() {
        val alert = AirAlerts.snapshot()
        val color = when (alert.level) {
            AirAlerts.Level.CITY -> Color.rgb(217, 48, 37)
            AirAlerts.Level.OBLAST -> Color.rgb(255, 194, 37)
            AirAlerts.Level.CLEAR -> Color.rgb(27, 156, 70)
            AirAlerts.Level.UNKNOWN -> Color.rgb(141, 150, 160)
        }
        paintAlertDot(color)
        val timeLabel = if (alert.sourceUpdatedUtcMs > 0L)
            " · ${kyivClock.format(Instant.ofEpochMilli(alert.sourceUpdatedUtcMs))}"
        else ""
        val caption = when (alert.level) {
            AirAlerts.Level.CITY -> "Киев: тревога"
            AirAlerts.Level.OBLAST -> "Тревога: область"
            AirAlerts.Level.CLEAR -> "Без тревог (по данным)"
            AirAlerts.Level.UNKNOWN -> "Нет данных о тревогах"
        }
        alertLabel.text = caption + timeLabel
        alertDot.contentDescription = alert.explanation
    }

    private fun addAlertHeader() {
        val top = LinearLayout(this).apply {
            orientation = LinearLayout.HORIZONTAL
            gravity = Gravity.CENTER_VERTICAL
        }
        top.addView(TextView(this).apply {
            text = "OBD GPS"
            textSize = 24f
            setTextColor(Color.BLACK)
            typeface = android.graphics.Typeface.DEFAULT_BOLD
        }, LinearLayout.LayoutParams(0, LinearLayout.LayoutParams.WRAP_CONTENT, 1f))

        val indicator = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            gravity = Gravity.RIGHT
        }
        alertDot = View(this).apply {
            isClickable = true
            setOnClickListener {
                Toast.makeText(this@MainActivity,
                    AirAlerts.snapshot().explanation + "\nTryvoha.online · неофициальные данные",
                    Toast.LENGTH_LONG).show()
            }
        }
        indicator.addView(alertDot, LinearLayout.LayoutParams(dip(22), dip(22)).apply {
            gravity = Gravity.RIGHT
        })
        alertLabel = TextView(this).apply {
            text = "Нет данных"
            textSize = 11f
            gravity = Gravity.RIGHT
            setTextColor(Color.DKGRAY)
            maxWidth = dip(140)
        }
        indicator.addView(alertLabel)
        top.addView(indicator)
        root.addView(top)
        showAlertStatus()
    }
    private var picker: AlertDialog? = null
    private var deviceAdapter: ArrayAdapter<String>? = null
    private var pickerKeys = listOf<String>()
    private fun updateDevicePicker() {
        val list = State.devices.toList()
        pickerKeys = list.map { it.first }
        deviceAdapter?.let { adapter ->
            adapter.clear()
            adapter.addAll(
                if (list.isEmpty()) listOf("Поиск устройств... Включи зажигание и Bluetooth")
                else list.map { (key, name) -> "$name\n${key.substringAfter('|')}" }
            )
            adapter.notifyDataSetChanged()
        }
    }
    private fun showDevicePicker() {
        picker?.dismiss()
        val adapter = ArrayAdapter<String>(this, android.R.layout.simple_list_item_1, mutableListOf())
        deviceAdapter = adapter
        val dialog = AlertDialog.Builder(this)
            .setTitle("Выбери Bluetooth ELM327")
            .setAdapter(adapter) { _, index ->
                pickerKeys.getOrNull(index)?.let { send(NavService.CONNECT, it) }
            }
            .setPositiveButton("Искать снова") { _, _ ->
                State.devices.clear()
                send(NavService.SCAN)
                showDevicePicker()
            }
            .setNegativeButton("Закрыть", null)
            .create()
        picker = dialog
        dialog.setOnDismissListener { if (picker === dialog) { picker = null; deviceAdapter = null } }
        dialog.show()
        updateDevicePicker()
    }
    private val refresh = object: Runnable {
        override fun run() {
            AirAlerts.refreshIfDue()
            showAlertStatus()
            val updatedByService=State.gpsSpeedUpdatedElapsedMs>0L
            val speedValue=if(updatedByService)State.gpsSpeedKmh else gpsSpeedKmh
            val speedTime=if(updatedByService)State.gpsSpeedUpdatedElapsedMs else gpsSpeedUpdatedElapsedMs
            gpsSpeedValue.text = if(isGpsEnabled()) speedLabel(speedValue,speedTime) else "—"
            obdSpeedValue.text = speedLabel(State.speed?.toDouble(),State.speedUpdatedElapsedMs)
            val bluetooth=if(isBluetoothEnabled())"вкл" else "выкл"
            val gps=if(isGpsEnabled())"вкл" else "выкл"
            status.text="Режим: ${State.navigationMode} · Авто: ${if(State.autoEnabled)"вкл" else "выкл"}\n"+
                "Bluetooth: $bluetooth · GPS: $gps\n"+
                "ELM: ${State.deviceName}\n"+
                "GPS: ${State.gpsText}\n"+
                "Протокол: ${State.modeLabel}\n"+
                "Статус: ${State.message}\n"+
                if(State.dr) "Путь: ${State.position}\nРост погрешности: ~${State.driftMeters.toInt()} м" else ""
            sensorStatus.text="Движение: ${State.motionText}\n"+
                "Ускорение: ${State.accelerationText}\n"+
                "Компас: ${State.compassStatus}\n"+
                "Направление: ${State.directionText}\n"+
                "Калибровка: ${State.calibrationText}\n"+
                State.sensorAvailability

            if (picker != null) updateDevicePicker()
            handler.postDelayed(this,750)
        }
    }
    private fun addButton(parent: LinearLayout, caption: String, click: ()->Unit) {
        parent.addView(Button(this).apply { text = caption; isAllCaps = false; setOnClickListener { click() } })
    }
    private fun send(action: String, address: String? = null) {
        if (!hasPermissions()) { checkBluetoothGps(); return }
        val i = Intent(this, NavService::class.java).setAction(action)
        if (address != null) i.putExtra("address",address)
        try { startForegroundService(i) } catch (e: Exception) { State.message = e.message ?: "Ошибка запуска" }
    }
    private fun hasPermissions() = arrayOf(
        Manifest.permission.ACCESS_FINE_LOCATION,
        Manifest.permission.BLUETOOTH_SCAN,
        Manifest.permission.BLUETOOTH_CONNECT
    ).all { checkSelfPermission(it) == PackageManager.PERMISSION_GRANTED }
    private fun askPermissions() {
        requestPermissions(arrayOf(Manifest.permission.ACCESS_FINE_LOCATION,
          Manifest.permission.ACCESS_COARSE_LOCATION,Manifest.permission.BLUETOOTH_SCAN,
          Manifest.permission.BLUETOOTH_CONNECT,Manifest.permission.POST_NOTIFICATIONS),12)
    }
    private fun chooseBluetooth() {
        if (!hasPermissions() || !isBluetoothEnabled()) {
            checkBluetoothGps()
        } else {
            State.devices.clear()
            send(NavService.SCAN)
            showDevicePicker()
        }
    }

    private fun showProtocolChoice() {
        val items=arrayOf("OBD2 K-Line (рабочий)", "Mitsubishi MUT-II (эксперимент)")
        AlertDialog.Builder(this).setTitle("Протокол OBD")
            .setSingleChoiceItems(items,if(State.mutMode)1 else 0) { dlg,index ->
                send(if(index==1) NavService.SET_MUT else NavService.SET_OBD)
                dlg.dismiss()
            }.setNegativeButton("Отмена",null).show()
    }

    private fun showDirectionChoice() {
        // Standard PID 010D reports speed magnitude, not transmission gear.
        AlertDialog.Builder(this).setTitle("Направление (ручной выбор)")
            .setSingleChoiceItems(arrayOf("Вперёд","Назад"),if(State.reverseSelected)1 else 0) { dlg,i ->
                send(if(i==1)NavService.REVERSE else NavService.FORWARD)
                dlg.dismiss()
            }.setNegativeButton("Отмена",null).show()
    }

    private fun showSettingsMenu() {
        val items=arrayOf(
            "Bluetooth: проверить и включить",
            "Bluetooth: выбрать адаптер ELM327",
            "OBD: выбрать протокол",
            "Датчики: калибровка на стоящей машине (5 с)",
            "Компас: согласовать с курсом GPS",
            "Направление: вперёд / назад",
            "Автоведение: включить / выключить",
            "Фиктивные местоположения Android",
            "Состояние датчиков"
        )
        AlertDialog.Builder(this).setTitle("Настройки").setItems(items) { _,index ->
            when(index) {
                0 -> checkBluetoothGps()
                1 -> chooseBluetooth()
                2 -> showProtocolChoice()
                3 -> {
                    send(NavService.CALIBRATE)
                    Toast.makeText(this,"Калибровка начата, телефон не двигать 5 секунд",Toast.LENGTH_LONG).show()
                }
                4 -> send(NavService.ALIGN_COMPASS)
                5 -> showDirectionChoice()
                6 -> {
                    val enable= !State.autoEnabled
                    send(if(enable)NavService.AUTO_ON else NavService.AUTO_OFF)
                }
                7 -> {
                    try { startActivity(Intent(Settings.ACTION_APPLICATION_DEVELOPMENT_SETTINGS)) }
                    catch (_: Exception) { startActivity(Intent(Settings.ACTION_SETTINGS)) }
                }
                8 -> AlertDialog.Builder(this).setTitle("Датчики")
                    .setMessage(State.sensorAvailability+"\n"+State.motionText+"\n"+
                        State.accelerationText+"\n"+State.compassStatus+"\n"+State.calibrationText)
                    .setPositiveButton("Закрыть",null).show()
            }
        }.setNegativeButton("Закрыть",null).show()
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val scroll = ScrollView(this).apply {
            setBackgroundColor(Color.WHITE)
            clipToPadding = false
            // Android 15/16 enforces edge-to-edge drawing: reserve the
            // status bar, display cutout and gesture navigation space.
            setOnApplyWindowInsetsListener { view, windowInsets ->
                val bars = windowInsets.getInsets(
                    WindowInsets.Type.systemBars() or WindowInsets.Type.displayCutout()
                )
                view.setPadding(bars.left, bars.top, bars.right, bars.bottom)
                windowInsets
            }
        }
        root = LinearLayout(this).apply { orientation=LinearLayout.VERTICAL; setPadding(30,30,30,40) }
        scroll.addView(root); setContentView(scroll)
        addAlertHeader()
        addSpeedPanels()
        status = TextView(this).apply {
            textSize = 15f
            setTextColor(Color.DKGRAY)
            setPadding(dip(4), dip(8), dip(4), dip(15))
        }
        root.addView(status)
        sensorStatus=TextView(this).apply {
            textSize=14f
            setTextColor(Color.DKGRAY)
            setPadding(dip(4),dip(7),dip(4),dip(15))
        }
        root.addView(sensorStatus)
        addButton(root,"Настройки") { showSettingsMenu() }
        addButton(root,"Принудительно: вести по датчикам") { send(NavService.START_DR) }
        addButton(root,"Вернуться к GPS") { send(NavService.STOP_DR) }
        addButton(root,"Открыть Google Maps") { openGoogleMaps() }
        addButton(root,"Остановить мониторинг") { send(NavService.EXIT) }
    }
    private fun openGoogleMaps() {
        val mapsPackage = "com.google.android.apps.maps"

        // Android 11+ package visibility: declared in AndroidManifest <queries>.
        // Prefer launching Maps normally, without forcing a destination.
        try {
            val launch = packageManager.getLaunchIntentForPackage(mapsPackage)
            if (launch != null) {
                startActivity(launch)
                return
            }
        } catch (_: Exception) {
            // Fall through to a verified ACTION_VIEW intent.
        }

        try {
            val mapsLink = Intent(Intent.ACTION_VIEW, Uri.parse("https://www.google.com/maps/"))
                .setPackage(mapsPackage)
            startActivity(mapsLink)
            return
        } catch (_: ActivityNotFoundException) {
            // Maps may be missing or disabled. Try a browser instead.
        } catch (_: SecurityException) {
            // The package may reject the intent; try the browser instead.
        }

        try {
            val browser = Intent(Intent.ACTION_VIEW, Uri.parse("https://www.google.com/maps/"))
                .addCategory(Intent.CATEGORY_BROWSABLE)
            startActivity(browser)
            State.message = "Google Maps открылся через браузер"
        } catch (e: Exception) {
            val error = "Не удалось открыть Google Maps: ${e.localizedMessage ?: "нет подходящего приложения"}"
            State.message = error
            Toast.makeText(this, error, Toast.LENGTH_LONG).show()
        }
    }
    override fun onResume() {
        super.onResume()
        monitorGpsSpeed()
        if(hasPermissions()) send(NavService.MONITOR)
        handler.removeCallbacks(refresh)
        handler.post(refresh)
    }

    override fun onPause() {
        handler.removeCallbacks(refresh)
        picker?.dismiss()
        try { locationManager.removeUpdates(gpsSpeedListener) } catch (_: Exception) {}
        super.onPause()
    }

    override fun onRequestPermissionsResult(
        requestCode: Int, permissions: Array<out String>, grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode == 12) {
            monitorGpsSpeed()
            handler.post { checkBluetoothGps() }
        }
    }
}
